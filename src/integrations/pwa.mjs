// Writes `sw.js` into the built site: an offline-first service worker with a
// precache manifest of the reading experience — every page except the
// finished-app source dump, which is runtime-cached on first visit — plus
// the shell (styles, fonts, scripts), the icons, and the search index.
//
// The cache version hashes the URL list, so a new build installs a new
// worker, activates it immediately, and deletes the old cache.
import { createHash } from 'node:crypto';
import { readdir, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

// The source dump is heavy (megabytes); it is cached the first time a reader
// opens it instead of up front.
const RUNTIME_PREFIX = 'appendices/the-finished-app/';

const EXACT = new Set([
	'/keys.js',
	'/tracker.js',
	'/manifest.webmanifest',
	'/favicon.svg',
]);

async function* walk(dir) {
	for (const entry of await readdir(dir, { withFileTypes: true })) {
		const path = join(dir, entry.name);
		if (entry.isDirectory()) yield* walk(path);
		else yield path;
	}
}

export default function pwa() {
	return {
		name: 'pwa',
		hooks: {
			'astro:build:done': async ({ dir, logger }) => {
				const root = fileURLToPath(dir);
				const urls = [];
				for await (const file of walk(root)) {
					const rel = '/' + relative(root, file).replaceAll('\\', '/');
					if (rel.startsWith(`/${RUNTIME_PREFIX}`)) continue;
					if (rel === '/sw.js') continue;
					if (rel.endsWith('.html')) {
						if (rel === '/404.html') continue;
						urls.push(rel === '/index.html' ? '/' : rel.replace(/index\.html$/, ''));
					} else if (
						rel.startsWith('/_astro/') ||
						rel.startsWith('/fonts/') ||
						rel.startsWith('/icons/') ||
						rel.startsWith('/pagefind/') ||
						EXACT.has(rel)
					) {
						urls.push(rel);
					}
				}
				urls.sort();
				const version = createHash('sha256').update(urls.join('\n')).digest('hex').slice(0, 12);

				const sw = `// Generated by src/integrations/pwa.mjs — do not edit by hand.
const VERSION = '${version}';
const PRECACHE = ${JSON.stringify(urls)};
const CACHE = 'gtb-' + VERSION;
const OFFLINE = '/offline/';

self.addEventListener('install', (event) => {
	event.waitUntil(
		(async () => {
			const cache = await caches.open(CACHE);
			// One by one: a single failed fetch must not abort the install.
			await Promise.all(PRECACHE.map((url) => cache.add(url).catch(() => {})));
			await self.skipWaiting();
		})()
	);
});

self.addEventListener('activate', (event) => {
	event.waitUntil(
		(async () => {
			for (const key of await caches.keys()) {
				if (key !== CACHE) await caches.delete(key);
			}
			await self.clients.claim();
		})()
	);
});

self.addEventListener('fetch', (event) => {
	const request = event.request;
	if (request.method !== 'GET') return;
	const url = new URL(request.url);
	if (url.origin !== self.location.origin) return;

	event.respondWith(
		(async () => {
			const cache = await caches.open(CACHE);
			const cached = await cache.match(request);
			if (cached) return cached;
			try {
				const response = await fetch(request);
				if (response.ok && (request.mode === 'navigate' || request.destination !== '')) {
					cache.put(request, response.clone());
				}
				return response;
			} catch {
				if (request.mode === 'navigate') {
					const offline = await cache.match(OFFLINE);
					if (offline) return offline;
				}
				return new Response('', { status: 503, statusText: 'offline' });
			}
		})()
	);
});
`;
				await writeFile(join(root, 'sw.js'), sw);
				logger.info(`wrote sw.js — ${urls.length} precached URLs, version ${version}`);
			},
		},
	};
}
